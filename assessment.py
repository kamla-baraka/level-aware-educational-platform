def calculate_score(answers):
    """Calculate the number of correct answers (0-10)."""
    return sum(
        answers.get(question["id"]) == question["answer"]
        for question in QUESTIONS
    )


def determine_level(score):
    """
    Preliminary level classification.
    Thresholds must be validated before research evaluation.
    """
    if not 0 <= score <= len(QUESTIONS):
        raise ValueError("Score must be between 0 and 10.")

    if score <= 3:
        return "Basic"
    elif score <= 7:
        return "Intermediate"
    else:
        return "Advanced"
